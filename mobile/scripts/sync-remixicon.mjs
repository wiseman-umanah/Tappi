// Copies the Remix Icon font into assets/ and writes a compact name -> codepoint map.
// Run after upgrading the `remixicon` package: pnpm icons:sync
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const fontsDir = dirname(require.resolve('remixicon/fonts/remixicon.glyph.json'));
const { version } = JSON.parse(readFileSync(join(fontsDir, '..', 'package.json'), 'utf8'));

mkdirSync(join(root, 'assets/fonts'), { recursive: true });
copyFileSync(join(fontsDir, 'remixicon.ttf'), join(root, 'assets/fonts/remixicon.ttf'));

const glyphs = JSON.parse(readFileSync(join(fontsDir, 'remixicon.glyph.json'), 'utf8'));
const entries = Object.entries(glyphs)
  .map(([name, { unicode }]) => [name, parseInt(unicode.replace(/^&#x|;$/g, ''), 16)])
  .sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([name, code]) => `  '${name}': ${code},`).join('\n');
writeFileSync(
  join(root, 'src/components/icon/glyphs.ts'),
  `// Generated by scripts/sync-remixicon.mjs from remixicon@${version}. Do not edit.\n` +
    `export const glyphs = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof glyphs;\n`,
);

console.log(`remixicon@${version}: ${entries.length} icons`);
